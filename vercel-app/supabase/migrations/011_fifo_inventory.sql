create table public.inventory_lots (
    id bigint generated by default as identity primary key,
    vegetable_id bigint not null references public.vegetables(id),
    harvest_id bigint references public.harvests(id),
    source_type text not null check (source_type in ('opening_balance', 'harvest', 'manual_addition')),
    received_on date not null,
    quantity_received numeric(14, 2) not null check (quantity_received > 0),
    quantity_remaining numeric(14, 2) not null check (
        quantity_remaining >= 0 and quantity_remaining <= quantity_received
    ),
    created_at timestamptz not null default now(),
    check ((source_type = 'harvest') = (harvest_id is not null))
);

create unique index inventory_lots_harvest_id_idx
    on public.inventory_lots(harvest_id)
    where harvest_id is not null;
create index inventory_lots_fifo_idx
    on public.inventory_lots(vegetable_id, source_type, received_on, id)
    where quantity_remaining > 0;

create table public.inventory_lot_allocations (
    id bigint generated by default as identity primary key,
    order_code varchar(24) not null references public.orders(order_code) on delete cascade,
    vegetable_id bigint not null references public.vegetables(id),
    inventory_lot_id bigint not null references public.inventory_lots(id),
    quantity numeric(14, 2) not null check (quantity > 0),
    released_at timestamptz,
    created_at timestamptz not null default now(),
    unique (order_code, vegetable_id, inventory_lot_id)
);

alter table public.inventory_lots enable row level security;
create policy "Farm staff can view FIFO inventory lots"
on public.inventory_lots for select to authenticated
using (public.is_farm_staff());
alter table public.inventory_lot_allocations enable row level security;
revoke all on public.inventory_lots from public, anon, authenticated, service_role;
revoke all on public.inventory_lot_allocations from public, anon, authenticated, service_role;
grant select on public.inventory_lots to authenticated;

with active_reservations as (
    select s.vegetable_id, sum(s.quantity) as quantity
    from public.sales s
    join public.orders o on o.order_code = s.order_code
    where o.order_status not in ('cancelled', 'delivered')
        and s.status <> 'cancelled'
    group by s.vegetable_id
)
insert into public.inventory_lots (
    vegetable_id, source_type, received_on, quantity_received, quantity_remaining
)
select
    v.id,
    'opening_balance',
    current_date,
    coalesce(i.quantity, 0) + coalesce(r.quantity, 0),
    coalesce(i.quantity, 0)
from public.vegetables v
left join public.inventory i on i.vegetable_id = v.id
left join active_reservations r on r.vegetable_id = v.id
where coalesce(i.quantity, 0) + coalesce(r.quantity, 0) > 0;

insert into public.inventory_lot_allocations (
    order_code, vegetable_id, inventory_lot_id, quantity
)
select s.order_code, s.vegetable_id, l.id, sum(s.quantity)
from public.sales s
join public.orders o on o.order_code = s.order_code
join public.inventory_lots l
    on l.vegetable_id = s.vegetable_id
    and l.source_type = 'opening_balance'
where o.order_status not in ('cancelled', 'delivered')
    and s.status <> 'cancelled'
group by s.order_code, s.vegetable_id, l.id;

create or replace function public.consume_fifo_lots(
    p_vegetable_id bigint,
    p_quantity numeric,
    p_order_code text default null
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    remaining_quantity numeric := round(p_quantity, 2);
    take_quantity numeric;
    lot_row record;
begin
    if p_quantity is null or p_quantity::text in ('NaN', 'Infinity', '-Infinity')
        or remaining_quantity <= 0 then
        raise exception 'FIFO stock quantity must be a positive finite number.';
    end if;

    for lot_row in
        select id, quantity_remaining
        from public.inventory_lots
        where vegetable_id = p_vegetable_id and quantity_remaining > 0
        order by
            case when source_type = 'opening_balance' then 0 else 1 end,
            received_on,
            id
        for update
    loop
        take_quantity := least(remaining_quantity, lot_row.quantity_remaining);
        update public.inventory_lots
        set quantity_remaining = quantity_remaining - take_quantity
        where id = lot_row.id;

        if p_order_code is not null then
            insert into public.inventory_lot_allocations as current_allocation (
                order_code, vegetable_id, inventory_lot_id, quantity
            )
            values (p_order_code, p_vegetable_id, lot_row.id, take_quantity)
            on conflict (order_code, vegetable_id, inventory_lot_id)
            do update set quantity =
                current_allocation.quantity + excluded.quantity;
        end if;

        remaining_quantity := remaining_quantity - take_quantity;
        exit when remaining_quantity = 0;
    end loop;

    if remaining_quantity > 0 then
        raise exception 'FIFO batches do not contain enough stock for this inventory change.';
    end if;
end;
$$;

create or replace function public.restore_fifo_lots(p_order_code text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    allocation_row record;
begin
    for allocation_row in
        select id, inventory_lot_id, quantity
        from public.inventory_lot_allocations
        where order_code = p_order_code and released_at is null
        order by id
        for update
    loop
        update public.inventory_lots
        set quantity_remaining = quantity_remaining + allocation_row.quantity
        where id = allocation_row.inventory_lot_id
            and quantity_remaining + allocation_row.quantity <= quantity_received;
        if not found then
            raise exception 'The reserved FIFO stock could not be restored safely.';
        end if;

        update public.inventory_lot_allocations
        set released_at = now()
        where id = allocation_row.id;
    end loop;
end;
$$;

create or replace function public.set_inventory(p_vegetable_id bigint, p_quantity numeric)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    current_quantity numeric;
    target_quantity numeric;
    difference numeric;
begin
    if not public.is_farm_staff() then
        raise exception 'Only farm staff can update inventory.';
    end if;
    if p_quantity is null or p_quantity < 0
        or p_quantity::text in ('NaN', 'Infinity', '-Infinity') then
        raise exception 'Inventory quantity must be a non-negative number.';
    end if;
    target_quantity := round(p_quantity, 2);
    insert into public.inventory (vegetable_id, quantity)
    values (p_vegetable_id, 0)
    on conflict (vegetable_id) do nothing;

    select quantity into current_quantity
    from public.inventory
    where vegetable_id = p_vegetable_id
    for update;
    if not found then raise exception 'Vegetable inventory was not found.'; end if;

    difference := target_quantity - current_quantity;
    if difference > 0 then
        insert into public.inventory_lots (
            vegetable_id, source_type, received_on, quantity_received, quantity_remaining
        )
        values (
            p_vegetable_id, 'manual_addition', current_date, difference, difference
        );
    elsif difference < 0 then
        perform public.consume_fifo_lots(p_vegetable_id, -difference);
    end if;

    update public.inventory
    set quantity = target_quantity, updated_at = now()
    where vegetable_id = p_vegetable_id;
    perform public.write_activity_log('updated', 'inventory', p_vegetable_id, 'Stock quantity changed');
end;
$$;

create or replace function public.create_harvest(
    p_planting_id bigint, p_quantity numeric, p_harvested_on date, p_quality_notes text
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    new_id bigint;
    vegetable_key bigint;
    harvest_quantity numeric := round(p_quantity, 2);
begin
    if not public.is_farm_staff() then raise exception 'Only farm staff can record harvests.'; end if;
    if p_quantity is null or p_quantity::text in ('NaN', 'Infinity', '-Infinity')
        or harvest_quantity <= 0 or char_length(coalesce(p_quality_notes, '')) > 4000 then
        raise exception 'Harvest quantity or notes are invalid.';
    end if;
    select vegetable_id into vegetable_key
    from public.plantings
    where id = p_planting_id and status = 'growing'
    for update;
    if not found then raise exception 'Choose a growing planting.'; end if;

    insert into public.harvests (planting_id, quantity, harvested_on, quality_notes)
    values (p_planting_id, harvest_quantity, p_harvested_on, nullif(p_quality_notes, ''))
    returning id into new_id;
    insert into public.inventory (vegetable_id, quantity)
    values (vegetable_key, harvest_quantity)
    on conflict (vegetable_id) do update
        set quantity = public.inventory.quantity + excluded.quantity, updated_at = now();
    insert into public.inventory_lots (
        vegetable_id, harvest_id, source_type, received_on, quantity_received, quantity_remaining
    )
    values (
        vegetable_key, new_id, 'harvest', p_harvested_on, harvest_quantity, harvest_quantity
    );
    perform public.write_activity_log('created', 'harvest', new_id, null);
    return new_id;
end;
$$;

create or replace function public.update_harvest(
    p_id bigint, p_quantity numeric, p_harvested_on date, p_quality_notes text
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    old_quantity numeric;
    vegetable_key bigint;
    current_quantity numeric;
    difference numeric;
    lot_key bigint;
    lot_remaining numeric;
    harvest_quantity numeric := round(p_quantity, 2);
begin
    if not public.is_farm_staff() then raise exception 'Only farm staff can update harvests.'; end if;
    if p_quantity is null or p_quantity::text in ('NaN', 'Infinity', '-Infinity')
        or harvest_quantity <= 0 or char_length(coalesce(p_quality_notes, '')) > 4000 then
        raise exception 'Harvest quantity or notes are invalid.';
    end if;
    select h.quantity, p.vegetable_id into old_quantity, vegetable_key
    from public.harvests h
    join public.plantings p on p.id = h.planting_id
    where h.id = p_id and h.archived_at is null
    for update of h;
    if not found then raise exception 'This harvest is no longer active.'; end if;

    insert into public.inventory (vegetable_id, quantity)
    values (vegetable_key, 0)
    on conflict (vegetable_id) do nothing;
    select quantity into current_quantity
    from public.inventory
    where vegetable_id = vegetable_key
    for update;

    select id, quantity_remaining
    into lot_key, lot_remaining
    from public.inventory_lots
    where harvest_id = p_id
    for update;
    difference := harvest_quantity - old_quantity;

    if found then
        if difference < 0 and lot_remaining < -difference then
            raise exception 'This harvest cannot be reduced below the quantity already allocated to orders.';
        end if;
        update public.inventory_lots
        set quantity_received = quantity_received + difference,
            quantity_remaining = quantity_remaining + difference,
            received_on = p_harvested_on
        where id = lot_key;
    elsif difference > 0 then
        insert into public.inventory_lots (
            vegetable_id, source_type, received_on, quantity_received, quantity_remaining
        )
        values (
            vegetable_key, 'manual_addition', p_harvested_on, difference, difference
        );
    elsif difference < 0 then
        if current_quantity < -difference then
            raise exception 'Inventory does not contain enough stock to reduce this harvest.';
        end if;
        perform public.consume_fifo_lots(vegetable_key, -difference);
    end if;

    if current_quantity + difference < 0 then
        raise exception 'Inventory does not contain enough stock to reduce this harvest.';
    end if;
    update public.inventory
    set quantity = current_quantity + difference, updated_at = now()
    where vegetable_id = vegetable_key;
    update public.harvests
    set quantity = harvest_quantity,
        harvested_on = p_harvested_on,
        quality_notes = nullif(p_quality_notes, '')
    where id = p_id;
    perform public.write_activity_log('updated', 'harvest', p_id, null);
end;
$$;

create or replace function public.archive_harvest(p_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    old_quantity numeric;
    vegetable_key bigint;
    current_quantity numeric;
    lot_key bigint;
    lot_remaining numeric;
    quantity_to_remove numeric;
begin
    if not public.is_farm_staff() then raise exception 'Only farm staff can archive harvests.'; end if;
    select h.quantity, p.vegetable_id into old_quantity, vegetable_key
    from public.harvests h
    join public.plantings p on p.id = h.planting_id
    where h.id = p_id and h.archived_at is null
    for update of h;
    if not found then raise exception 'This harvest is already archived.'; end if;

    select quantity into current_quantity
    from public.inventory
    where vegetable_id = vegetable_key
    for update;
    if not found then raise exception 'Inventory does not contain this harvest stock.'; end if;

    select id, quantity_remaining into lot_key, lot_remaining
    from public.inventory_lots
    where harvest_id = p_id
    for update;
    if found then
        quantity_to_remove := lot_remaining;
        update public.inventory_lots set quantity_remaining = 0 where id = lot_key;
    else
        quantity_to_remove := old_quantity;
        if current_quantity < quantity_to_remove then
            raise exception 'Inventory does not contain enough stock to archive this harvest.';
        end if;
        perform public.consume_fifo_lots(vegetable_key, quantity_to_remove);
    end if;

    if current_quantity < quantity_to_remove then
        raise exception 'Inventory does not contain enough stock to archive this harvest.';
    end if;
    update public.inventory
    set quantity = current_quantity - quantity_to_remove, updated_at = now()
    where vegetable_id = vegetable_key;
    update public.harvests set archived_at = now() where id = p_id;
    perform public.write_activity_log('archived', 'harvest', p_id, null);
end;
$$;

create or replace function public.create_order(
    p_items jsonb, p_delivery_address text, p_payment_method text, p_checkout_token text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    buyer_key bigint := public.current_profile_id();
    token_hash text;
    request_hash text;
    existing_order public.orders%rowtype;
    normalized_items jsonb;
    order_key bigint;
    order_number text;
    subtotal_value numeric := 0;
    eligible_value numeric := 0;
    discount_rate numeric := 0;
    discount_value numeric := 0;
    delivery_value numeric := 20;
    cart_item jsonb;
    product_key bigint;
    quantity_value numeric;
    price_value numeric;
    line_total numeric;
    stock_value numeric;
begin
    if buyer_key is null or public.current_role() <> 'buyer' then raise exception 'A buyer account is required.'; end if;
    if p_payment_method not in ('cod', 'online') then raise exception 'Choose a supported payment method.'; end if;
    if char_length(trim(p_delivery_address)) < 10 or char_length(trim(p_delivery_address)) > 1000 then
        raise exception 'Delivery address must be between 10 and 1,000 characters.';
    end if;
    if p_checkout_token is null or p_checkout_token !~ '^[a-f0-9]{64}$' then
        raise exception 'Checkout token is invalid; reload checkout.';
    end if;
    if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'Your cart is empty.'; end if;

    select jsonb_agg(jsonb_build_object('id', item_id, 'quantity', item_quantity) order by item_id)
    into normalized_items
    from (
        select (value ->> 'id')::bigint as item_id,
            sum(round((value ->> 'quantity')::numeric, 2)) as item_quantity
        from jsonb_array_elements(p_items)
        group by (value ->> 'id')::bigint
    ) cart;
    if normalized_items is null or exists (
        select 1
        from jsonb_array_elements(normalized_items) as cart_entry(value)
        where (cart_entry.value ->> 'quantity')::numeric <= 0
            or (cart_entry.value ->> 'quantity')::numeric > 10000
            or (cart_entry.value ->> 'quantity')::numeric::text in ('NaN', 'Infinity', '-Infinity')
    ) then
        raise exception 'Cart quantity is invalid.';
    end if;

    token_hash := encode(extensions.digest(p_checkout_token, 'sha256'), 'hex');
    perform pg_advisory_xact_lock(hashtextextended(buyer_key::text || token_hash, 0));
    request_hash := encode(extensions.digest(jsonb_build_object(
        'items', normalized_items, 'address', trim(p_delivery_address), 'payment_method', p_payment_method
    )::text, 'sha256'), 'hex');
    select * into existing_order from public.orders
    where buyer_id = buyer_key and checkout_token_hash = token_hash;
    if found then
        if existing_order.checkout_request_hash <> request_hash then
            raise exception 'This checkout form was already used for a different order.';
        end if;
        return to_jsonb(existing_order);
    end if;

    for cart_item in
        select value
        from jsonb_array_elements(normalized_items)
        order by (value ->> 'id')::bigint
    loop
        product_key := (cart_item ->> 'id')::bigint;
        quantity_value := (cart_item ->> 'quantity')::numeric;
        if quantity_value <= 0 or quantity_value > 10000 then raise exception 'Cart quantity is invalid.'; end if;
        select v.price, i.quantity into price_value, stock_value
        from public.vegetables v
        join public.inventory i on i.vegetable_id = v.id
        where v.id = product_key and v.active
        for update of i;
        if not found then raise exception 'A cart item is no longer available.'; end if;
        if stock_value < quantity_value then raise exception 'There is not enough stock to complete this order.'; end if;
        eligible_value := eligible_value + quantity_value;
        subtotal_value := subtotal_value + round(price_value * quantity_value, 2);
    end loop;
    subtotal_value := round(subtotal_value, 2);
    eligible_value := round(eligible_value, 2);
    if eligible_value >= 20 then discount_rate := 10; end if;
    discount_value := round(subtotal_value * discount_rate / 100, 2);

    order_number := 'VS-' || to_char(clock_timestamp(), 'YYMMDDHH24MISS')
        || upper(substr(encode(extensions.gen_random_bytes(4), 'hex'), 1, 8));
    insert into public.orders (
        order_code, buyer_id, checkout_token_hash, checkout_request_hash,
        subtotal, eligible_quantity, discount_percentage, discount_amount, delivery_fee,
        final_total, delivery_address, payment_method, payment_status, order_status
    ) values (
        order_number, buyer_key, token_hash, request_hash,
        subtotal_value, eligible_value, discount_rate, discount_value, delivery_value,
        round(subtotal_value - discount_value + delivery_value, 2), trim(p_delivery_address),
        p_payment_method, 'pending_payment', 'confirmed'
    ) returning id into order_key;

    for cart_item in
        select value
        from jsonb_array_elements(normalized_items)
        order by (value ->> 'id')::bigint
    loop
        product_key := (cart_item ->> 'id')::bigint;
        quantity_value := (cart_item ->> 'quantity')::numeric;
        select price into price_value from public.vegetables where id = product_key and active;
        line_total := round(price_value * quantity_value, 2);
        update public.inventory
        set quantity = quantity - quantity_value, updated_at = now()
        where vegetable_id = product_key and quantity >= quantity_value;
        if not found then raise exception 'Inventory changed while placing the order; please retry.'; end if;
        perform public.consume_fifo_lots(product_key, quantity_value, order_number);
        insert into public.sales (order_code, buyer_id, vegetable_id, quantity, unit_price, total)
        values (order_number, buyer_key, product_key, round(quantity_value, 2), price_value, line_total);
    end loop;

    insert into public.payment_history (order_code, payment_method, event_type, payment_status, amount, actor_id)
    values (order_number, p_payment_method, 'order_created', 'pending_payment',
        round(subtotal_value - discount_value + delivery_value, 2), buyer_key);
    perform public.write_activity_log('created', 'order', order_key, order_number);
    select * into existing_order from public.orders where id = order_key;
    return to_jsonb(existing_order);
end;
$$;

create or replace function public.update_order_status(p_order_code text, p_status text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare current_order public.orders%rowtype;
begin
    if not public.is_farm_staff() then raise exception 'Only farm staff can update orders.'; end if;
    select * into current_order from public.orders where order_code = p_order_code for update;
    if not found then raise exception 'Order not found.'; end if;
    if p_status = 'cancelled' then
        if current_order.order_status = 'cancelled' then raise exception 'This order is already cancelled.'; end if;
        if current_order.payment_status in ('paid', 'refunded') or current_order.order_status = 'delivered' then
            raise exception 'This order cannot be cancelled.';
        end if;
        if current_order.payment_method = 'online' and current_order.gateway_expired_at is null then
            raise exception 'Online checkout must be expired before stock can be released.';
        end if;
        update public.inventory i set quantity = i.quantity + s.quantity, updated_at = now()
        from public.sales s where s.order_code = current_order.order_code
            and i.vegetable_id = s.vegetable_id and s.status <> 'cancelled';
        perform public.restore_fifo_lots(current_order.order_code);
        update public.sales set status = 'cancelled' where order_code = current_order.order_code;
        update public.orders set order_status = 'cancelled', payment_status = 'failed', updated_at = now()
        where order_code = current_order.order_code;
        insert into public.payment_history (order_code, payment_method, event_type, payment_status, amount, actor_id)
        values (current_order.order_code, current_order.payment_method, 'order_cancelled',
            'failed', current_order.final_total, public.current_profile_id());
    else
        if not (
            (current_order.order_status = 'pending' and p_status = 'confirmed')
            or (current_order.order_status = 'confirmed' and p_status = 'preparing')
            or (current_order.order_status = 'preparing' and p_status = 'ready_for_delivery')
            or (current_order.order_status = 'ready_for_delivery' and p_status = 'out_for_delivery')
            or (current_order.order_status = 'out_for_delivery' and p_status = 'delivered')
        ) then raise exception 'That order status transition is not allowed.'; end if;
        update public.orders set order_status = p_status, updated_at = now() where order_code = p_order_code;
    end if;
    perform public.write_activity_log('updated', 'order', current_order.id, p_status);
end;
$$;

create or replace function public.rollback_online_checkout(p_order_code text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare current_order public.orders%rowtype;
begin
    if auth.role() <> 'service_role' then raise exception 'Not authorized.'; end if;
    select * into current_order from public.orders where order_code = p_order_code for update;
    if not found or current_order.payment_method <> 'online'
        or current_order.payment_status <> 'pending_payment'
        or current_order.gateway_session_id is not null then
        raise exception 'The checkout is no longer safe to roll back.';
    end if;
    update public.inventory i set quantity = i.quantity + s.quantity, updated_at = now()
    from public.sales s where s.order_code = p_order_code
        and i.vegetable_id = s.vegetable_id and s.status <> 'cancelled';
    perform public.restore_fifo_lots(p_order_code);
    update public.sales set status = 'cancelled' where order_code = p_order_code;
    update public.orders set payment_status = 'failed', order_status = 'cancelled',
        updated_at = now() where order_code = p_order_code;
end;
$$;

revoke all on function public.consume_fifo_lots(bigint, numeric, text) from public, anon, authenticated;
revoke all on function public.restore_fifo_lots(text) from public, anon, authenticated;
