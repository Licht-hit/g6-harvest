create extension if not exists pgcrypto;

create table public.profiles (
    id bigint generated by default as identity primary key,
    auth_user_id uuid not null unique references auth.users(id) on delete cascade,
    name text not null,
    email text not null unique,
    role text not null default 'buyer' check (role in ('admin', 'staff', 'buyer')),
    email_verified_at timestamptz,
    created_at timestamptz not null default now()
);

create table public.vegetables (
    id bigint generated by default as identity primary key,
    name varchar(120) not null,
    variety varchar(120),
    description text,
    unit varchar(30) not null default 'kg',
    price numeric(10, 2) not null default 0 check (price >= 0 and price <> 'NaN'::numeric),
    active boolean not null default true,
    created_at timestamptz not null default now()
);

create table public.inventory (
    vegetable_id bigint primary key references public.vegetables(id),
    quantity numeric(10, 2) not null default 0 check (quantity >= 0 and quantity <> 'NaN'::numeric),
    updated_at timestamptz not null default now()
);

create table public.plantings (
    id bigint generated by default as identity primary key,
    vegetable_id bigint not null references public.vegetables(id),
    quantity_planted numeric(10, 2) not null check (quantity_planted > 0),
    planted_on date not null,
    expected_harvest_on date,
    status text not null default 'growing' check (status in ('growing', 'harvested', 'cancelled')),
    created_at timestamptz not null default now()
);

create table public.harvests (
    id bigint generated by default as identity primary key,
    planting_id bigint not null references public.plantings(id),
    quantity numeric(10, 2) not null check (quantity > 0),
    harvested_on date not null,
    quality_notes text,
    archived_at timestamptz,
    created_at timestamptz not null default now()
);

create table public.orders (
    id bigint generated by default as identity primary key,
    order_code varchar(24) not null unique,
    buyer_id bigint not null references public.profiles(id),
    checkout_token_hash char(64),
    checkout_request_hash char(64),
    gateway_checkout_url text,
    subtotal numeric(10, 2) not null,
    eligible_quantity numeric(10, 2) not null default 0,
    discount_percentage numeric(5, 2) not null default 0,
    discount_amount numeric(10, 2) not null default 0,
    delivery_fee numeric(10, 2) not null default 0,
    final_total numeric(10, 2) not null,
    delivery_address text not null,
    payment_method text not null check (payment_method in ('cod', 'online', 'legacy')),
    payment_status text not null default 'pending_payment'
        check (payment_status in ('pending_payment', 'paid', 'failed', 'refunded')),
    order_status text not null default 'pending'
        check (order_status in ('pending', 'confirmed', 'preparing', 'ready_for_delivery', 'out_for_delivery', 'delivered', 'cancelled')),
    payment_reference varchar(120),
    gateway_session_id varchar(120),
    gateway_expired_at timestamptz,
    payment_confirmed_by bigint references public.profiles(id) on delete set null,
    payment_confirmed_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (buyer_id, checkout_token_hash)
);

create index orders_buyer_id_idx on public.orders(buyer_id);
create index orders_payment_status_idx on public.orders(payment_status);
create index orders_created_at_idx on public.orders(created_at);
create index orders_payment_reference_idx on public.orders(payment_reference);

create table public.sales (
    id bigint generated by default as identity primary key,
    order_code varchar(24) not null references public.orders(order_code) on delete cascade,
    buyer_id bigint not null references public.profiles(id),
    vegetable_id bigint not null references public.vegetables(id),
    quantity numeric(10, 2) not null check (quantity > 0),
    unit_price numeric(10, 2) not null check (unit_price >= 0),
    total numeric(10, 2) not null check (total >= 0),
    status text not null default 'pending' check (status in ('pending', 'paid', 'cancelled')),
    created_at timestamptz not null default now()
);

create index sales_order_code_idx on public.sales(order_code);

create table public.payment_history (
    id bigint generated by default as identity primary key,
    order_code varchar(24) not null references public.orders(order_code) on delete cascade,
    payment_method text not null check (payment_method in ('cod', 'online', 'legacy')),
    event_type varchar(60) not null,
    payment_status text not null check (payment_status in ('pending_payment', 'paid', 'failed', 'refunded')),
    amount numeric(10, 2) not null,
    payment_reference varchar(120),
    provider_event_id varchar(160) unique,
    actor_id bigint references public.profiles(id) on delete set null,
    details varchar(255),
    created_at timestamptz not null default now()
);

create index payment_history_order_idx on public.payment_history(order_code, created_at);

create table public.quality_inspections (
