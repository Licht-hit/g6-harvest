create or replace function public.create_profile_for_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare profile_key bigint;
begin
    insert into public.profiles (auth_user_id, name, email, email_verified_at)
    values (
        new.id,
        coalesce(new.raw_user_meta_data ->> 'name', split_part(new.email, '@', 1)),
        new.email,
        new.email_confirmed_at
    )
    on conflict (auth_user_id) do update
        set email = excluded.email,
            email_verified_at = coalesce(public.profiles.email_verified_at, excluded.email_verified_at)
    returning id into profile_key;
    if tg_op = 'INSERT' then
        insert into public.activity_logs (user_id, action, entity_type, entity_id, details)
        values (profile_key, 'account_created', 'account', profile_key, 'New account registered');
    elsif old.email_confirmed_at is null and new.email_confirmed_at is not null then
        update public.profiles set email_verified_at = new.email_confirmed_at where id = profile_key;
        insert into public.activity_logs (user_id, action, entity_type, entity_id, details)
        values (profile_key, 'email_verified', 'account', profile_key, 'Email address verified');
    end if;
    return new;
end;
$$;

create trigger auth_user_profile_created
after insert or update of email, email_confirmed_at on auth.users
for each row execute function public.create_profile_for_auth_user();

