create or replace function public.set_inventory(p_vegetable_id bigint, p_quantity numeric)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    if not public.is_farm_staff() then
        raise exception 'Only farm staff can update inventory.';
    end if;
    if p_quantity < 0 or p_quantity::text in ('NaN', 'Infinity', '-Infinity') then
        raise exception 'Inventory quantity must be a non-negative number.';
    end if;
    insert into public.inventory (vegetable_id, quantity, updated_at)
    values (p_vegetable_id, round(p_quantity, 2), now())
    on conflict (vegetable_id) do update
        set quantity = excluded.quantity, updated_at = now();
    perform public.write_activity_log('updated', 'inventory', p_vegetable_id, 'Stock quantity changed');
end;
$$;

create or replace function public.create_planting(
    p_vegetable_id bigint, p_quantity numeric, p_planted_on date, p_expected_harvest_on date
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare new_id bigint;
begin
    if not public.is_farm_staff() then raise exception 'Only farm staff can create plantings.'; end if;
    if p_quantity <= 0 or not exists (select 1 from public.vegetables where id = p_vegetable_id and active) then
        raise exception 'Choose an active vegetable and a positive quantity.';
    end if;
    if p_expected_harvest_on is not null and p_expected_harvest_on < p_planted_on then
        raise exception 'Expected harvest date cannot be before planting date.';
    end if;
    insert into public.plantings (vegetable_id, quantity_planted, planted_on, expected_harvest_on)
    values (p_vegetable_id, round(p_quantity, 2), p_planted_on, p_expected_harvest_on)
    returning id into new_id;
    perform public.write_activity_log('created', 'planting', new_id, null);
    return new_id;
end;
$$;

create or replace function public.update_planting(
    p_id bigint, p_vegetable_id bigint, p_quantity numeric, p_planted_on date, p_expected_harvest_on date
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    if not public.is_farm_staff() then raise exception 'Only farm staff can update plantings.'; end if;
    if p_quantity <= 0
        or (p_expected_harvest_on is not null and p_expected_harvest_on < p_planted_on)
        or not exists (select 1 from public.vegetables where id = p_vegetable_id and active) then
        raise exception 'Planting dates or quantity are invalid.';
    end if;
    update public.plantings
    set vegetable_id = p_vegetable_id, quantity_planted = round(p_quantity, 2), planted_on = p_planted_on,
        expected_harvest_on = p_expected_harvest_on
    where id = p_id and status = 'growing';
    if not found then raise exception 'Only growing plantings can be edited.'; end if;
    perform public.write_activity_log('updated', 'planting', p_id, null);
end;
$$;

