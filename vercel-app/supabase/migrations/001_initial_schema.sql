create or replace function public.create_harvest(
    p_planting_id bigint, p_quantity numeric, p_harvested_on date, p_quality_notes text
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare new_id bigint; vegetable_key bigint;
begin
    if not public.is_farm_staff() then raise exception 'Only farm staff can record harvests.'; end if;
    if p_quantity <= 0 or char_length(coalesce(p_quality_notes, '')) > 4000 then
        raise exception 'Harvest quantity or notes are invalid.';
    end if;
    select vegetable_id into vegetable_key from public.plantings
    where id = p_planting_id and status = 'growing' for update;
    if not found then raise exception 'Choose a growing planting.'; end if;
    insert into public.harvests (planting_id, quantity, harvested_on, quality_notes)
    values (p_planting_id, round(p_quantity, 2), p_harvested_on, nullif(p_quality_notes, ''))
    returning id into new_id;
    insert into public.inventory (vegetable_id, quantity)
    values (vegetable_key, round(p_quantity, 2))
    on conflict (vegetable_id) do update
        set quantity = public.inventory.quantity + excluded.quantity, updated_at = now();
    perform public.write_activity_log('created', 'harvest', new_id, null);
    return new_id;
end;
$$;

create or replace function public.update_harvest(
    p_id bigint, p_quantity numeric, p_harvested_on date, p_quality_notes text
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare old_quantity numeric; vegetable_key bigint; difference numeric;
begin
    if not public.is_farm_staff() then raise exception 'Only farm staff can update harvests.'; end if;
    if p_quantity <= 0 or char_length(coalesce(p_quality_notes, '')) > 4000 then
        raise exception 'Harvest quantity or notes are invalid.';
    end if;
    select h.quantity, p.vegetable_id into old_quantity, vegetable_key
    from public.harvests h join public.plantings p on p.id = h.planting_id
    where h.id = p_id and h.archived_at is null for update of h;
    if not found then raise exception 'This harvest is no longer active.'; end if;
    difference := round(p_quantity, 2) - old_quantity;
    if difference < 0 then
        update public.inventory set quantity = quantity + difference, updated_at = now()
        where vegetable_id = vegetable_key and quantity + difference >= 0;
        if not found then raise exception 'Inventory does not contain enough stock to reduce this harvest.'; end if;
    else
        insert into public.inventory (vegetable_id, quantity)
        values (vegetable_key, difference)
        on conflict (vegetable_id) do update
            set quantity = public.inventory.quantity + excluded.quantity, updated_at = now();
    end if;
    update public.harvests set quantity = round(p_quantity, 2), harvested_on = p_harvested_on,
        quality_notes = nullif(p_quality_notes, '') where id = p_id;
    perform public.write_activity_log('updated', 'harvest', p_id, null);
end;
$$;

create or replace function public.archive_harvest(p_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare old_quantity numeric; vegetable_key bigint;
begin
    if not public.is_farm_staff() then raise exception 'Only farm staff can archive harvests.'; end if;
    select h.quantity, p.vegetable_id into old_quantity, vegetable_key
    from public.harvests h join public.plantings p on p.id = h.planting_id
    where h.id = p_id and h.archived_at is null for update of h;
    if not found then raise exception 'This harvest is already archived.'; end if;
    update public.inventory set quantity = quantity - old_quantity, updated_at = now()
    where vegetable_id = vegetable_key and quantity >= old_quantity;
    if not found then raise exception 'Inventory does not contain enough stock to archive this harvest.'; end if;
    update public.harvests set archived_at = now() where id = p_id;
    perform public.write_activity_log('archived', 'harvest', p_id, null);
end;
$$;

create or replace function public.create_order(
    p_items jsonb, p_delivery_address text, p_payment_method text, p_checkout_token text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    buyer_key bigint := public.current_profile_id();
    token_hash text;
    request_hash text;
    existing_order public.orders%rowtype;
    normalized_items jsonb;
    order_key bigint;
    order_number text;
    subtotal_value numeric := 0;
    eligible_value numeric := 0;
    discount_rate numeric := 0;
    discount_value numeric := 0;
    delivery_value numeric := 20;
    item jsonb;
    product_key bigint;
    quantity_value numeric;
    price_value numeric;
    line_total numeric;
    stock_value numeric;
begin
    if buyer_key is null or public.current_role() <> 'buyer' then raise exception 'A buyer account is required.'; end if;
    if p_payment_method not in ('cod', 'online') then raise exception 'Choose a supported payment method.'; end if;
    if char_length(trim(p_delivery_address)) < 10 or char_length(trim(p_delivery_address)) > 1000 then
        raise exception 'Delivery address must be between 10 and 1,000 characters.';
    end if;
    if p_checkout_token is null or p_checkout_token !~ '^[a-f0-9]{64}$' then
        raise exception 'Checkout token is invalid; reload checkout.';
    end if;
    if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'Your cart is empty.'; end if;

    select jsonb_agg(jsonb_build_object('id', item_id, 'quantity', item_quantity) order by item_id)
    into normalized_items
    from (
        select (value ->> 'id')::bigint as item_id,
            sum(round((value ->> 'quantity')::numeric, 2)) as item_quantity
        from jsonb_array_elements(p_items)
        group by (value ->> 'id')::bigint
    ) cart;
    if normalized_items is null or exists (
        select 1
        from jsonb_array_elements(normalized_items) item
        where (item ->> 'quantity')::numeric <= 0
            or (item ->> 'quantity')::numeric > 10000
            or (item ->> 'quantity')::numeric::text in ('NaN', 'Infinity', '-Infinity')
    ) then
        raise exception 'Cart quantity is invalid.';
    end if;

    token_hash := encode(digest(p_checkout_token, 'sha256'), 'hex');
    perform pg_advisory_xact_lock(hashtextextended(buyer_key::text || token_hash, 0));
    request_hash := encode(digest(jsonb_build_object(
        'items', normalized_items, 'address', trim(p_delivery_address), 'payment_method', p_payment_method
    )::text, 'sha256'), 'hex');
    select * into existing_order from public.orders
    where buyer_id = buyer_key and checkout_token_hash = token_hash;
    if found then
        if existing_order.checkout_request_hash <> request_hash then
            raise exception 'This checkout form was already used for a different order.';
        end if;
        return to_jsonb(existing_order);
    end if;

    for item in select value from jsonb_array_elements(normalized_items) order by (value ->> 'id')::bigint loop
        product_key := (item ->> 'id')::bigint;
        quantity_value := (item ->> 'quantity')::numeric;
        if quantity_value <= 0 or quantity_value > 10000 then raise exception 'Cart quantity is invalid.'; end if;
        select v.price, i.quantity into price_value, stock_value
        from public.vegetables v join public.inventory i on i.vegetable_id = v.id
        where v.id = product_key and v.active for update of i;
        if not found then raise exception 'A cart item is no longer available.'; end if;
        if stock_value < quantity_value then raise exception 'There is not enough stock to complete this order.'; end if;
        eligible_value := eligible_value + quantity_value;
        subtotal_value := subtotal_value + round(price_value * quantity_value, 2);
    end loop;
    subtotal_value := round(subtotal_value, 2);
    eligible_value := round(eligible_value, 2);
    if eligible_value >= 20 then discount_rate := 10; end if;
    discount_value := round(subtotal_value * discount_rate / 100, 2);

    order_number := 'VS-' || to_char(clock_timestamp(), 'YYMMDDHH24MISS') || upper(substr(encode(gen_random_bytes(4), 'hex'), 1, 8));
    insert into public.orders (
        order_code, buyer_id, checkout_token_hash, checkout_request_hash,
        subtotal, eligible_quantity, discount_percentage, discount_amount, delivery_fee,
        final_total, delivery_address, payment_method, payment_status, order_status
    ) values (
        order_number, buyer_key, token_hash, request_hash,
        subtotal_value, eligible_value, discount_rate, discount_value, delivery_value,
        round(subtotal_value - discount_value + delivery_value, 2), trim(p_delivery_address),
        p_payment_method, 'pending_payment', 'confirmed'
    ) returning id into order_key;

    for item in select value from jsonb_array_elements(normalized_items) order by (value ->> 'id')::bigint loop
        product_key := (item ->> 'id')::bigint;
        quantity_value := (item ->> 'quantity')::numeric;
        select price into price_value from public.vegetables where id = product_key and active;
        line_total := round(price_value * quantity_value, 2);
        update public.inventory set quantity = quantity - quantity_value, updated_at = now()
        where vegetable_id = product_key and quantity >= quantity_value;
        if not found then raise exception 'Inventory changed while placing the order; please retry.'; end if;
        insert into public.sales (order_code, buyer_id, vegetable_id, quantity, unit_price, total)
        values (order_number, buyer_key, product_key, round(quantity_value, 2), price_value, line_total);
    end loop;

    insert into public.payment_history (order_code, payment_method, event_type, payment_status, amount, actor_id)
    values (order_number, p_payment_method, 'order_created', 'pending_payment',
        round(subtotal_value - discount_value + delivery_value, 2), buyer_key);
    perform public.write_activity_log('created', 'order', order_key, order_number);
    select * into existing_order from public.orders where id = order_key;
    return to_jsonb(existing_order);
end;
$$;

create or replace function public.update_order_status(p_order_code text, p_status text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare current_order public.orders%rowtype;
begin
    if not public.is_farm_staff() then raise exception 'Only farm staff can update orders.'; end if;
    select * into current_order from public.orders where order_code = p_order_code for update;
    if not found then raise exception 'Order not found.'; end if;
    if p_status = 'cancelled' then
        if current_order.payment_status in ('paid', 'refunded') or current_order.order_status = 'delivered' then
            raise exception 'This order cannot be cancelled.';
        end if;
        if current_order.payment_method = 'online' and current_order.gateway_expired_at is null then
            raise exception 'Online checkout must be expired before stock can be released.';
        end if;
        update public.inventory i set quantity = i.quantity + s.quantity, updated_at = now()
        from public.sales s where s.order_code = current_order.order_code
            and i.vegetable_id = s.vegetable_id and s.status <> 'cancelled';
        update public.sales set status = 'cancelled' where order_code = current_order.order_code;
        update public.orders set order_status = 'cancelled', payment_status = 'failed', updated_at = now()
        where order_code = current_order.order_code;
        insert into public.payment_history (order_code, payment_method, event_type, payment_status, amount, actor_id)
        values (current_order.order_code, current_order.payment_method, 'order_cancelled',
            'failed', current_order.final_total, public.current_profile_id());
    else
        if not (
            (current_order.order_status = 'pending' and p_status = 'confirmed')
            or (current_order.order_status = 'confirmed' and p_status = 'preparing')
            or (current_order.order_status = 'preparing' and p_status = 'ready_for_delivery')
            or (current_order.order_status = 'ready_for_delivery' and p_status = 'out_for_delivery')
            or (current_order.order_status = 'out_for_delivery' and p_status = 'delivered')
        ) then raise exception 'That order status transition is not allowed.'; end if;
        update public.orders set order_status = p_status, updated_at = now() where order_code = p_order_code;
    end if;
    perform public.write_activity_log('updated', 'order', current_order.id, p_status);
end;
$$;

create or replace function public.confirm_cod_collection(p_order_code text, p_reference text default null)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare current_order public.orders%rowtype; actor_key bigint := public.current_profile_id();
begin
    if not public.is_farm_staff() then raise exception 'Only farm staff can confirm cash collection.'; end if;
    select * into current_order from public.orders where order_code = p_order_code for update;
    if not found or current_order.payment_method <> 'cod'
        or current_order.payment_status <> 'pending_payment'
        or current_order.order_status not in ('out_for_delivery', 'delivered') then
        raise exception 'Cash can be confirmed only for an out-for-delivery or delivered COD order.';
    end if;
    update public.orders set payment_status = 'paid', payment_reference = nullif(p_reference, ''),
        payment_confirmed_by = actor_key, payment_confirmed_at = now(), updated_at = now()
    where order_code = p_order_code;
    update public.sales set status = 'paid' where order_code = p_order_code;
    insert into public.payment_history (order_code, payment_method, event_type, payment_status,
        amount, payment_reference, actor_id)
    values (p_order_code, 'cod', 'cod_collected', 'paid', current_order.final_total,
        nullif(p_reference, ''), actor_key);
    perform public.write_activity_log('confirmed_payment', 'order', current_order.id, p_order_code);
end;
$$;

create or replace function public.rollback_online_checkout(p_order_code text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare current_order public.orders%rowtype;
begin
    if auth.role() <> 'service_role' then raise exception 'Not authorized.'; end if;
    select * into current_order from public.orders where order_code = p_order_code for update;
    if not found or current_order.payment_method <> 'online'
        or current_order.payment_status <> 'pending_payment'
        or current_order.gateway_session_id is not null then
        raise exception 'The checkout is no longer safe to roll back.';
    end if;
    update public.inventory i set quantity = i.quantity + s.quantity, updated_at = now()
    from public.sales s where s.order_code = p_order_code
        and i.vegetable_id = s.vegetable_id and s.status <> 'cancelled';
    update public.sales set status = 'cancelled' where order_code = p_order_code;
    update public.orders set payment_status = 'failed', order_status = 'cancelled',
        updated_at = now() where order_code = p_order_code;
end;
$$;

create or replace function public.apply_paymongo_event(
    p_event_id text, p_event_type text, p_session_id text, p_amount_cents bigint, p_reference text
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare current_order public.orders%rowtype; next_status text;
begin
    if auth.role() <> 'service_role' then raise exception 'Not authorized.'; end if;
    select * into current_order from public.orders where gateway_session_id = p_session_id for update;
    if not found or current_order.payment_method <> 'online' then raise exception 'Payment order was not found.'; end if;
    if exists (select 1 from public.payment_history where provider_event_id = p_event_id) then return; end if;
    if p_event_type = 'checkout_session.payment.paid' then
        if p_amount_cents is null then raise exception 'Payment amount is missing.'; end if;
        if p_amount_cents <> round(current_order.final_total * 100)::bigint then
            raise exception 'Payment amount does not match the order total.';
        end if;
        next_status := 'paid';
        update public.sales set status = 'paid' where order_code = current_order.order_code;
    elsif p_event_type = 'checkout_session.payment.failed' then
        next_status := 'failed';
    elsif p_event_type = 'payment.refunded' then
        if p_amount_cents is null then raise exception 'Refund amount is missing.'; end if;
        if p_amount_cents <> round(current_order.final_total * 100)::bigint then
            raise exception 'Refund amount does not match the order total.';
        end if;
        if current_order.payment_status <> 'paid' then raise exception 'Only paid orders can be refunded.'; end if;
        next_status := 'refunded';
    else
        raise exception 'Unsupported PayMongo event.';
    end if;
    update public.orders set payment_status = next_status,
        payment_reference = coalesce(nullif(p_reference, ''), payment_reference),
        updated_at = now() where order_code = current_order.order_code;
    insert into public.payment_history (order_code, payment_method, event_type, payment_status,
        amount, payment_reference, provider_event_id)
    values (current_order.order_code, 'online', p_event_type, next_status,
        case when p_event_type = 'payment.refunded' then current_order.final_total else current_order.final_total end,
        nullif(p_reference, ''), p_event_id);
end;
$$;

create or replace function public.add_quality_inspection(
    p_harvest_id bigint, p_grade text, p_notes text, p_inspected_on date
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare new_id bigint;
begin
    if not public.is_farm_staff() then raise exception 'Only farm staff can record inspections.'; end if;
    if p_grade not in ('A', 'B', 'C', 'Rejected') or char_length(coalesce(p_notes, '')) > 4000 then
        raise exception 'Inspection grade or notes are invalid.';
    end if;
    if not exists (select 1 from public.harvests where id = p_harvest_id and archived_at is null) then
        raise exception 'Choose an active harvest.';
    end if;
    insert into public.quality_inspections (harvest_id, inspector_id, grade, notes, inspected_on)
    values (p_harvest_id, public.current_profile_id(), p_grade, nullif(p_notes, ''), p_inspected_on)
    returning id into new_id;
    perform public.write_activity_log('created', 'quality_inspection', new_id, p_grade);
    return new_id;
end;
$$;

create or replace function public.reset_identity_sequences()
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare table_name text; sequence_name text; maximum_id bigint;
begin
    if auth.role() <> 'service_role' then raise exception 'Not authorized.'; end if;
    foreach table_name in array array[
        'vegetables', 'plantings', 'harvests', 'orders', 'sales',
        'payment_history', 'quality_inspections', 'activity_logs'
    ] loop
        sequence_name := pg_get_serial_sequence('public.' || table_name, 'id');
        execute format('select max(id) from public.%I', table_name) into maximum_id;
        if maximum_id is not null then
            perform setval(sequence_name::regclass, maximum_id, true);
        end if;
    end loop;
end;
$$;

