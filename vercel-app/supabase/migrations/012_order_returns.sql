alter table public.orders
    add column delivered_at timestamptz;

update public.orders
set delivered_at = updated_at
where order_status = 'delivered' and delivered_at is null;

create or replace function public.record_order_delivery_time()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
    if new.order_status = 'delivered' and old.order_status is distinct from 'delivered' then
        new.delivered_at := now();
    end if;
    return new;
end;
$$;

create trigger orders_record_delivery_time
before update of order_status on public.orders
for each row execute function public.record_order_delivery_time();

revoke all on function public.record_order_delivery_time() from public, anon, authenticated;

create table public.return_requests (
    id bigint generated by default as identity primary key,
    order_code varchar(24) not null references public.orders(order_code),
    buyer_id bigint not null references public.profiles(id),
    reason text not null check (reason in ('damaged', 'quality_issue')),
    notes text check (notes is null or char_length(notes) <= 2000),
    status text not null default 'pending'
        check (status in ('pending', 'approved', 'rejected', 'completed')),
    staff_notes text check (staff_notes is null or char_length(staff_notes) <= 2000),
    requested_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    reviewed_at timestamptz,
    reviewed_by bigint references public.profiles(id) on delete set null,
    completed_at timestamptz
);

create index return_requests_order_idx on public.return_requests(order_code, requested_at);
create index return_requests_buyer_idx on public.return_requests(buyer_id, requested_at);
create index return_requests_status_idx on public.return_requests(status, requested_at);

create table public.return_request_items (
    id bigint generated by default as identity primary key,
    return_request_id bigint not null
        references public.return_requests(id) on delete cascade,
    sales_id bigint not null references public.sales(id),
    quantity numeric(10, 2) not null check (quantity > 0),
    unique (return_request_id, sales_id)
);

create index return_request_items_sales_idx on public.return_request_items(sales_id);

alter table public.return_requests enable row level security;
alter table public.return_request_items enable row level security;

create policy "Buyers and farm staff can view return requests"
on public.return_requests for select to authenticated
using (buyer_id = public.current_profile_id() or public.is_farm_staff());

create policy "Buyers and farm staff can view return request items"
on public.return_request_items for select to authenticated
using (
    exists (
        select 1
        from public.return_requests r
        where r.id = return_request_id
            and (r.buyer_id = public.current_profile_id() or public.is_farm_staff())
    )
);

revoke all on public.return_requests from public, anon, authenticated, service_role;
revoke all on public.return_request_items from public, anon, authenticated, service_role;
grant select on public.return_requests, public.return_request_items to authenticated;

create or replace function public.create_return_request(
    p_order_code text,
    p_items jsonb,
    p_reason text,
    p_notes text default null
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    buyer_key bigint := public.current_profile_id();
    current_order public.orders%rowtype;
    normalized_items jsonb;
    item_row jsonb;
    sale_key bigint;
    requested_quantity numeric;
    sold_quantity numeric;
    already_requested numeric;
    return_request_key bigint;
begin
    if buyer_key is null or public.current_role() <> 'buyer' then
        raise exception 'A buyer account is required to request a return.';
    end if;
    if p_reason is null or p_reason not in ('damaged', 'quality_issue') then
        raise exception 'Returns are accepted only for damaged items or quality issues.';
    end if;
    if char_length(coalesce(p_notes, '')) > 2000 then
        raise exception 'Return notes cannot exceed 2,000 characters.';
    end if;
    if p_items is null or jsonb_typeof(p_items) <> 'array' then
        raise exception 'Select at least one order item to return.';
    end if;
    if jsonb_array_length(p_items) = 0 then
        raise exception 'Select at least one order item to return.';
    end if;
    if exists (
        select 1
        from jsonb_array_elements(p_items) as entry(value)
        where jsonb_typeof(entry.value) <> 'object'
            or coalesce(entry.value ->> 'sales_id', '') !~ '^[1-9][0-9]*$'
            or coalesce(entry.value ->> 'quantity', '') !~ '^[0-9]+([.][0-9]{1,2})?$'
    ) then
        raise exception 'A return item or quantity is invalid.';
    end if;

    select jsonb_agg(jsonb_build_object('sales_id', sales_id, 'quantity', requested_quantity) order by sales_id)
    into normalized_items
    from (
        select (entry.value ->> 'sales_id')::bigint as sales_id,
            sum(round((entry.value ->> 'quantity')::numeric, 2)) as requested_quantity
        from jsonb_array_elements(p_items) as entry(value)
        group by (entry.value ->> 'sales_id')::bigint
    ) items;

    select * into current_order
    from public.orders
    where order_code = p_order_code and buyer_id = buyer_key
    for update;
    if not found then raise exception 'Order not found.'; end if;
    if current_order.order_status <> 'delivered'
        or current_order.delivered_at is null
        or current_order.delivered_at > now()
        or current_order.delivered_at < now() - interval '24 hours' then
        raise exception 'Return requests must be submitted within 24 hours after delivery.';
    end if;

    for item_row in
        select value
        from jsonb_array_elements(normalized_items)
        order by (value ->> 'sales_id')::bigint
    loop
        sale_key := (item_row ->> 'sales_id')::bigint;
        requested_quantity := round((item_row ->> 'quantity')::numeric, 2);
        if requested_quantity <= 0 or requested_quantity > 10000 then
            raise exception 'Return quantities must be positive and no more than 10,000.';
        end if;

        select quantity into sold_quantity
        from public.sales
        where id = sale_key
            and order_code = current_order.order_code
            and buyer_id = buyer_key
            and status <> 'cancelled'
        for update;
        if not found then raise exception 'A selected item does not belong to this order.'; end if;

        select coalesce(sum(rri.quantity), 0) into already_requested
        from public.return_request_items rri
        join public.return_requests rr on rr.id = rri.return_request_id
        where rri.sales_id = sale_key
            and rr.status in ('pending', 'approved', 'completed');
        if requested_quantity > sold_quantity - already_requested then
            raise exception 'The requested return quantity exceeds the unreturned quantity.';
        end if;
    end loop;

    insert into public.return_requests (order_code, buyer_id, reason, notes)
    values (current_order.order_code, buyer_key, p_reason, nullif(trim(p_notes), ''))
    returning id into return_request_key;

    for item_row in select value from jsonb_array_elements(normalized_items) loop
        insert into public.return_request_items (return_request_id, sales_id, quantity)
        values (
            return_request_key,
            (item_row ->> 'sales_id')::bigint,
            round((item_row ->> 'quantity')::numeric, 2)
        );
    end loop;

    perform public.write_activity_log(
        'created', 'return_request', return_request_key,
        'Return request submitted for order ' || current_order.order_code
    );
    return return_request_key;
end;
$$;

create or replace function public.update_return_request(
    p_request_id bigint,
    p_status text,
    p_staff_notes text default null
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    current_request public.return_requests%rowtype;
    request_order_code text;
    next_status text;
begin
    if not public.is_farm_staff() then
        raise exception 'Only farm staff can review return requests.';
    end if;
    if p_status is null or p_status not in ('approved', 'rejected', 'completed') then
        raise exception 'Choose an allowed return-request status.';
    end if;
    if char_length(coalesce(p_staff_notes, '')) > 2000 then
        raise exception 'Staff notes cannot exceed 2,000 characters.';
    end if;

    select order_code into request_order_code
    from public.return_requests
    where id = p_request_id;
    if not found then raise exception 'Return request not found.'; end if;
    perform 1 from public.orders where order_code = request_order_code for update;
    if not found then raise exception 'The return order was not found.'; end if;
    select * into current_request
    from public.return_requests
    where id = p_request_id
    for update;
    if not found then raise exception 'Return request not found.'; end if;

    if current_request.status = 'pending' and p_status in ('approved', 'rejected') then
        next_status := p_status;
    elsif current_request.status = 'approved' and p_status = 'completed' then
        next_status := p_status;
    else
        raise exception 'That return-request status transition is not allowed.';
    end if;
    if next_status = 'rejected' and nullif(trim(p_staff_notes), '') is null then
        raise exception 'Add a reason before rejecting a return request.';
    end if;

    update public.return_requests
    set status = next_status,
        staff_notes = coalesce(nullif(trim(p_staff_notes), ''), staff_notes),
        updated_at = now(),
        reviewed_at = now(),
        reviewed_by = public.current_profile_id(),
        completed_at = case
            when next_status = 'completed' then now()
            else completed_at
        end
    where id = p_request_id;
    perform public.write_activity_log(
        'updated', 'return_request', p_request_id,
        'Return request ' || next_status || ' for order ' || request_order_code
    );
end;
$$;

revoke all on function public.create_return_request(text, jsonb, text, text) from public, anon;
revoke all on function public.update_return_request(bigint, text, text) from public, anon;
grant execute on function public.create_return_request(text, jsonb, text, text) to authenticated;
grant execute on function public.update_return_request(bigint, text, text) to authenticated;
